def main() -> None:
    venues = [build_conference(c) for c in CONF] + [build_journal(j) for j in JOUR]
    doc = {
        "schema_version": 1,
        "updated_at": deadlines.iso_local(),
        "notes": "confirmed=官网核验；scraped=自动抓取；predicted=按历年规律推测。期刊为滚动投稿。",
        "venues": venues,
    }
    out = ROOT / "data" / "venues.json"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(json.dumps(doc, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(f"wrote {len(venues)} venues -> {out}")


